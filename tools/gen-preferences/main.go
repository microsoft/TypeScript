package main

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"go/token"
	"io"
	"os"
	"slices"
	"strconv"
	"strings"
)

type schema struct {
	Schema  string                `json:"$schema"`
	Ref     string                `json:"$ref"`
	Comment string                `json:"$comment"`
	Defs    map[string]definition `json:"$defs"`
}

type definition struct {
	Type        string              `json:"type"`
	Description string              `json:"description"`
	AllOf       []reference         `json:"allOf"`
	Properties  map[string]property `json:"properties"`
}

type reference struct {
	Ref string `json:"$ref"`
}

type property struct {
	Type           string    `json:"type"`
	Description    string    `json:"description"`
	Enum           []string  `json:"enum"`
	Items          *property `json:"items"`
	GoType         string    `json:"x-go-type"`
	Config         string    `json:"x-config"`
	FallbackConfig string    `json:"x-fallback-config"`
	GoUnderlying   string    `json:"x-go-underlying"`
	Default        string    `json:"default"`
	AcceptNumber   bool      `json:"x-accept-number"`
	ConfigParser   string    `json:"x-config-parser"`
	Validator      string    `json:"x-validator"`
}

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "Usage: gen-preferences <schema>.json <output>.go <output>.ts")
		os.Exit(1)
	}
	goOutput, tsOutput, err := generate(os.Args[1])
	if err == nil {
		err = os.WriteFile(os.Args[2], goOutput, 0o644)
	}
	if err == nil {
		err = os.WriteFile(os.Args[3], tsOutput, 0o644)
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(path string) ([]byte, []byte, error) {
	input, err := os.ReadFile(path)
	if err != nil {
		return nil, nil, err
	}
	var model schema
	decoder := json.NewDecoder(bytes.NewReader(input))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&model); err != nil {
		return nil, nil, fmt.Errorf("decode preference schema: %w", err)
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return nil, nil, errors.New("preference schema must contain one JSON object")
	}
	for _, def := range model.Defs {
		for name, prop := range def.Properties {
			if len(prop.Enum) != 0 && prop.GoType == "" {
				prop.GoType = goName(name)
				def.Properties[name] = prop
			}
		}
	}
	if _, err := model.resolve(model.Ref); err != nil {
		return nil, nil, err
	}
	names := sortedKeys(model.Defs)
	for _, name := range names {
		if _, err := model.fields(name, map[string]bool{}); err != nil {
			return nil, nil, err
		}
	}

	var goOutput, tsOutput bytes.Buffer
	goOutput.WriteString("// Code generated by gen-preferences from tools/userPreferences.schema.json; DO NOT EDIT.\n\npackage lsutil\n\n")
	tsOutput.WriteString("// Code generated by gen-preferences from tools/userPreferences.schema.json; DO NOT EDIT.\n\n")
	imports := map[string]string{}
	var goTypes bytes.Buffer
	for _, name := range names {
		def := model.Defs[name]
		writeDescription(&goTypes, def.Description, "// ")
		fmt.Fprintf(&goTypes, "type %s struct {\n", name)
		writeDescription(&tsOutput, def.Description, "")
		fmt.Fprintf(&tsOutput, "export interface %s", name)
		var bases []string
		for _, ref := range def.AllOf {
			base, _ := model.resolve(ref.Ref)
			bases = append(bases, base)
			fmt.Fprintf(&goTypes, "%s\n", base)
		}
		if len(bases) != 0 {
			fmt.Fprintf(&tsOutput, " extends %s", strings.Join(bases, ", "))
		}
		tsOutput.WriteString(" {\n")
		for _, wireName := range sortedKeys(def.Properties) {
			prop := def.Properties[wireName]
			fieldName := goName(wireName)
			goType, _ := prop.goType()
			for alias, path := range map[string]string{
				"core":             "github.com/microsoft/TypeScript/tsc/internal/core",
				"modulespecifiers": "github.com/microsoft/TypeScript/tsc/internal/modulespecifiers",
			} {
				if strings.HasPrefix(goType, alias+".") {
					imports[alias] = path
				}
			}
			writeDescription(&goTypes, prop.Description, "// ")
			fmt.Fprintf(&goTypes, "%s %s `json:%s", fieldName, goType, strconv.Quote(wireName+",omitempty"))
			goTypes.WriteString("`\n")
			writeDescription(&tsOutput, prop.Description, "    ")
			tsType, _ := prop.tsType()
			fmt.Fprintf(&tsOutput, "    %s?: %s | undefined;\n", wireName, tsType)
		}
		goTypes.WriteString("}\n\n")
		tsOutput.WriteString("}\n\n")
	}
	if err := model.writePreferenceMethods(&goTypes, imports); err != nil {
		return nil, nil, err
	}
	if len(imports) != 0 {
		goOutput.WriteString("import (\n")
		for _, alias := range sortedKeys(imports) {
			fmt.Fprintf(&goOutput, "%q\n", imports[alias])
		}
		goOutput.WriteString(")\n\n")
	}
	goOutput.Write(goTypes.Bytes())
	formatted, formatErr := format.Source(goOutput.Bytes())
	if formatErr != nil {
		return nil, nil, fmt.Errorf("format generated preferences: %w", formatErr)
	}
	return formatted, tsOutput.Bytes(), nil
}

func (s schema) resolve(ref string) (string, error) {
	name, ok := strings.CutPrefix(ref, "#/$defs/")
	if !ok {
		return "", fmt.Errorf("unsupported preference schema reference %q", ref)
	}
	if _, ok := s.Defs[name]; !ok {
		return "", fmt.Errorf("unknown preference schema reference %q", ref)
	}
	return name, nil
}

func (s schema) fields(name string, visiting map[string]bool) (map[string]bool, error) {
	if visiting[name] {
		return nil, fmt.Errorf("cyclic preference inheritance at %s", name)
	}
	if !token.IsIdentifier(name) || !token.IsExported(name) {
		return nil, fmt.Errorf("invalid preference definition name %q", name)
	}
	visiting[name] = true
	defer delete(visiting, name)
	def := s.Defs[name]
	if def.Type != "object" {
		return nil, fmt.Errorf("%s: preference definitions must be objects", name)
	}
	fields := map[string]bool{}
	goFields := map[string]bool{}
	for _, ref := range def.AllOf {
		base, err := s.resolve(ref.Ref)
		if err != nil {
			return nil, err
		}
		goField := base
		if !token.IsIdentifier(goField) || !token.IsExported(goField) || goFields[goField] {
			return nil, fmt.Errorf("%s: invalid or duplicate Go field %q", name, goField)
		}
		goFields[goField] = true
		inherited, err := s.fields(base, visiting)
		if err != nil {
			return nil, err
		}
		for field := range inherited {
			if fields[field] {
				return nil, fmt.Errorf("%s: duplicate inherited preference %q", name, field)
			}
			fields[field] = true
		}
	}
	for _, field := range sortedKeys(def.Properties) {
		prop := def.Properties[field]
		if !token.IsIdentifier(field) {
			return nil, fmt.Errorf("%s: invalid preference field %q", name, field)
		}
		fieldName := goName(field)
		if !token.IsIdentifier(fieldName) || !token.IsExported(fieldName) || goFields[fieldName] {
			return nil, fmt.Errorf("%s: invalid or duplicate preference field %q", name, field)
		}
		if fields[field] {
			return nil, fmt.Errorf("%s: duplicate inherited preference %q", name, field)
		}
		if _, err := prop.goType(); err != nil {
			return nil, fmt.Errorf("%s.%s: %w", name, field, err)
		}
		if _, err := prop.tsType(); err != nil {
			return nil, fmt.Errorf("%s.%s: %w", name, field, err)
		}
		if err := prop.validateParsing(); err != nil {
			return nil, fmt.Errorf("%s.%s: %w", name, field, err)
		}
		if strings.ContainsAny(prop.Config+prop.FallbackConfig, "`\r\n") {
			return nil, fmt.Errorf("%s.%s: invalid configuration tag", name, field)
		}
		goFields[fieldName] = true
		fields[field] = true
	}
	return fields, nil
}

func goName(name string) string {
	var result strings.Builder
	for part := range strings.SplitSeq(name, "-") {
		if part != "" {
			result.WriteString(strings.ToUpper(part[:1]))
			result.WriteString(part[1:])
		}
	}
	return result.String()
}

func (p property) goType() (string, error) {
	if p.GoType != "" {
		parts := strings.Split(p.GoType, ".")
		if len(parts) > 2 || len(parts) == 2 && parts[0] != "core" && parts[0] != "modulespecifiers" {
			return "", fmt.Errorf("unsupported Go preference type %q", p.GoType)
		}
		for _, part := range parts {
			if !token.IsIdentifier(part) {
				return "", fmt.Errorf("invalid Go preference type %q", p.GoType)
			}
		}
		return p.GoType, nil
	}
	switch p.Type {
	case "boolean":
		return "core.Tristate", nil
	case "integer":
		return "int", nil
	case "string":
		return "string", nil
	case "array":
		if p.Items != nil && p.Items.Type == "string" && len(p.Items.Enum) == 0 {
			return "[]string", nil
		}
	}
	return "", fmt.Errorf("unsupported Go preference type for %q", p.Type)
}

func (p property) tsType() (string, error) {
	if len(p.Enum) != 0 {
		if p.Type != "string" {
			return "", errors.New("preference enums must have string values")
		}
		var values []string
		for _, value := range p.Enum {
			quoted := strconv.Quote(value)
			if slices.Contains(values, quoted) {
				return "", fmt.Errorf("duplicate preference enum value %q", value)
			}
			values = append(values, quoted)
		}
		return strings.Join(values, " | "), nil
	}
	switch p.Type {
	case "boolean", "string":
		return p.Type, nil
	case "integer":
		return "number", nil
	case "array":
		if p.Items != nil && p.Items.Type == "string" && len(p.Items.Enum) == 0 {
			return "string[]", nil
		}
	}
	return "", fmt.Errorf("unsupported TypeScript preference type %q", p.Type)
}

func writeDescription(out *bytes.Buffer, description, prefix string) {
	if description == "" {
		return
	}
	if prefix == "// " {
		for line := range strings.SplitSeq(description, "\n") {
			fmt.Fprintf(out, "// %s\n", line)
		}
		return
	}
	fmt.Fprintf(out, "%s/**\n", prefix)
	for line := range strings.SplitSeq(description, "\n") {
		fmt.Fprintf(out, "%s * %s\n", prefix, strings.ReplaceAll(line, "*/", "*\\/"))
	}
	fmt.Fprintf(out, "%s */\n", prefix)
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	slices.Sort(keys)
	return keys
}
