package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/constant"
	"go/types"
	"os"
	"path/filepath"
	"reflect"
	"slices"
	"sort"
	"strconv"
	"strings"

	"golang.org/x/tools/go/packages"
)

func main() {
	os.Exit(run())
}

func run() int {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "Usage: gen-proto <input path>.go <output path>.ts")
		return 1
	}
	if err := generate(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	return 0
}

type methodInfo struct {
	name           string
	params         types.Type
	result         types.Type
	paramsText     string
	resultText     string
	resultNullable bool
}

func generate(inputPath string, outputPath string) error {
	absInput, err := filepath.Abs(inputPath)
	if err != nil {
		return err
	}

	cfg := &packages.Config{
		Mode: packages.NeedName | packages.NeedFiles | packages.NeedCompiledGoFiles |
			packages.NeedSyntax | packages.NeedTypes | packages.NeedTypesInfo |
			packages.NeedImports | packages.NeedDeps,
		Dir: filepath.Dir(absInput),
	}
	pkgs, err := packages.Load(cfg, ".")
	if err != nil {
		return fmt.Errorf("load API package: %w", err)
	}
	if len(pkgs) != 1 {
		return fmt.Errorf("load API package: expected one package, got %d", len(pkgs))
	}
	if packages.PrintErrors(pkgs) != 0 {
		return errors.New("load API package: package contains errors")
	}
	pkg := pkgs[0]

	inputFile := findSyntaxFile(pkg, absInput)
	if inputFile == nil {
		return fmt.Errorf("input file %q was not part of package %q", absInput, pkg.PkgPath)
	}

	methods, methodObjects, err := declaredMethods(pkg, inputFile)
	if err != nil {
		return err
	}
	resultTypeOverrides, nullableResults, err := discoverResultMetadata(pkg)
	if err != nil {
		return err
	}
	discoverSessionMethods(pkg, methodObjects, methods, resultTypeOverrides, nullableResults)
	discoverConnectionMethods(pkg, methodObjects, methods)

	for _, method := range methods {
		if method.paramsText == "" && method.params == nil {
			return fmt.Errorf("method %q has no request dispatch", method.name)
		}
		if method.resultText == "" && method.result == nil {
			return fmt.Errorf("method %q has no result type", method.name)
		}
	}
	// release is an ownership notification from the client's perspective. The
	// server's internal bool acknowledgement is deliberately not part of the API.
	for _, method := range methods {
		if method.name == "release" || method.name == "startCPUProfile" {
			method.result = nil
			method.resultText = "void"
		}
	}

	renderer := newTypeRenderer(pkg)
	var methodsOut bytes.Buffer
	methodsOut.WriteString("export type APIMethod<TParams, TResult> = { params: TParams; result: TResult; };\n\n")
	methodsOut.WriteString("export interface APIMethodInfo {\n")
	for _, method := range methods {
		params := method.paramsText
		if params == "" {
			params = renderer.requestType(method.params)
		}
		result := method.resultText
		if result == "" {
			result = renderer.resultType(method.result, method.resultNullable)
		}
		fmt.Fprintf(&methodsOut, "    %s: APIMethod<%s, %s>;\n", propertyName(method.name), params, result)
	}
	methodsOut.WriteString("}\n")

	declarations, err := renderer.declarations()
	if err != nil {
		return err
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by gen-proto; DO NOT EDIT.\n\n")
	if imports := renderer.importDeclarations(); imports != "" {
		out.WriteString(imports)
		out.WriteString("\n")
	}
	out.Write(methodsOut.Bytes())
	if declarations != "" {
		out.WriteString("\n")
		out.WriteString(declarations)
	}

	absOutput, err := filepath.Abs(outputPath)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(absOutput), 0o755); err != nil {
		return err
	}
	data := bytes.ReplaceAll(out.Bytes(), []byte{'\n'}, []byte{'\r', '\n'})
	if err := os.WriteFile(absOutput, data, 0o644); err != nil {
		return fmt.Errorf("write output: %w", err)
	}
	return nil
}

func findSyntaxFile(pkg *packages.Package, path string) *ast.File {
	cleanPath := filepath.Clean(path)
	for i, filePath := range pkg.CompiledGoFiles {
		if filepath.Clean(filePath) == cleanPath {
			return pkg.Syntax[i]
		}
	}
	return nil
}

func declaredMethods(pkg *packages.Package, file *ast.File) ([]*methodInfo, map[types.Object]*methodInfo, error) {
	var methods []*methodInfo
	methodObjects := make(map[types.Object]*methodInfo)
	for _, decl := range file.Decls {
		genDecl, ok := decl.(*ast.GenDecl)
		if !ok || genDecl.Tok.String() != "const" {
			continue
		}
		for _, spec := range genDecl.Specs {
			valueSpec := spec.(*ast.ValueSpec)
			for _, name := range valueSpec.Names {
				if !strings.HasPrefix(name.Name, "Method") {
					continue
				}
				obj := pkg.TypesInfo.Defs[name]
				constantObject, ok := obj.(*types.Const)
				if !ok || constantObject.Val().Kind() != constant.String {
					return nil, nil, fmt.Errorf("%s is not a string method constant", name.Name)
				}
				method := &methodInfo{name: constant.StringVal(constantObject.Val())}
				methods = append(methods, method)
				methodObjects[obj] = method
			}
		}
	}
	return methods, methodObjects, nil
}

func discoverResultMetadata(pkg *packages.Package) (map[types.Object]types.Type, map[types.Object]bool, error) {
	const resultDirective = "@gen-proto-result:"
	const nullableDirective = "@gen-proto-nullable"
	overrides := make(map[types.Object]types.Type)
	nullableResults := make(map[types.Object]bool)
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			fn, ok := decl.(*ast.FuncDecl)
			if !ok || fn.Doc == nil {
				continue
			}
			fnObject := pkg.TypesInfo.Defs[fn.Name]
			for _, comment := range fn.Doc.List {
				text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
				if text == nullableDirective {
					nullableResults[fnObject] = true
					continue
				}
				typeName, ok := strings.CutPrefix(text, resultDirective)
				if !ok {
					continue
				}
				typeName = strings.TrimSpace(typeName)
				typeObject, ok := pkg.Types.Scope().Lookup(typeName).(*types.TypeName)
				if !ok {
					return nil, nil, fmt.Errorf("result type override on %s refers to unknown type %q", fn.Name.Name, typeName)
				}
				overrides[fnObject] = typeObject.Type()
			}
		}
	}
	return overrides, nullableResults, nil
}

func discoverSessionMethods(pkg *packages.Package, methodObjects map[types.Object]*methodInfo, methods []*methodInfo, resultTypeOverrides map[types.Object]types.Type, nullableResults map[types.Object]bool) {
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			fn, isFuncDecl := decl.(*ast.FuncDecl)
			if !isFuncDecl || fn.Name.Name != "HandleRequest" || fn.Recv == nil || fn.Body == nil {
				continue
			}
			ast.Inspect(fn.Body, func(node ast.Node) bool {
				clause, isCaseClause := node.(*ast.CaseClause)
				if !isCaseClause || len(clause.List) != 1 {
					return true
				}
				method := methodForExpression(pkg, methodObjects, clause.List[0])
				if method == nil {
					return true
				}

				method.paramsText = "null"
				ast.Inspect(clause, func(child ast.Node) bool {
					assertion, isTypeAssertion := child.(*ast.TypeAssertExpr)
					if !isTypeAssertion || assertion.Type == nil {
						return true
					}
					if ident, isIdent := assertion.X.(*ast.Ident); isIdent && ident.Name == "parsed" {
						method.params = pkg.TypesInfo.TypeOf(assertion.Type)
						method.paramsText = ""
					}
					return true
				})

				for _, stmt := range clause.Body {
					returnStmt, isReturnStmt := stmt.(*ast.ReturnStmt)
					if !isReturnStmt || len(returnStmt.Results) == 0 {
						continue
					}
					call, isCall := returnStmt.Results[0].(*ast.CallExpr)
					if !isCall {
						continue
					}
					sig, isSignature := types.Unalias(pkg.TypesInfo.TypeOf(call.Fun)).(*types.Signature)
					if isSignature && sig.Results().Len() > 0 {
						method.result = sig.Results().At(0).Type()
					}
					called := calledObject(pkg, call.Fun)
					if override := resultTypeOverrides[called]; override != nil {
						method.result = override
					}
					method.resultNullable = nullableResults[called]
				}
				return false
			})
		}
	}

	for _, method := range methods {
		if method.params != nil && method.paramsText == "null" {
			method.paramsText = ""
		}
	}
}

func calledObject(pkg *packages.Package, expr ast.Expr) types.Object {
	switch expr := expr.(type) {
	case *ast.Ident:
		return pkg.TypesInfo.Uses[expr]
	case *ast.SelectorExpr:
		if selection := pkg.TypesInfo.Selections[expr]; selection != nil {
			return selection.Obj()
		}
		return pkg.TypesInfo.Uses[expr.Sel]
	default:
		return nil
	}
}

func discoverConnectionMethods(pkg *packages.Package, methodObjects map[types.Object]*methodInfo, methods []*methodInfo) {
	missing := make(map[*methodInfo]bool)
	for _, method := range methods {
		missing[method] = method.params == nil && method.paramsText == ""
	}
	for _, file := range pkg.Syntax {
		ast.Inspect(file, func(node ast.Node) bool {
			clause, isCaseClause := node.(*ast.CaseClause)
			if !isCaseClause || len(clause.List) != 1 {
				return true
			}
			method := methodForExpression(pkg, methodObjects, clause.List[0])
			if method == nil || !missing[method] {
				return true
			}
			ast.Inspect(clause, func(child ast.Node) bool {
				call, isCall := child.(*ast.CallExpr)
				if !isCall || len(call.Args) < 2 {
					return true
				}
				selector, isSelector := call.Fun.(*ast.SelectorExpr)
				if !isSelector || selector.Sel.Name != "WriteResponse" {
					return true
				}
				method.paramsText = "void"
				if ident, isIdent := call.Args[1].(*ast.Ident); isIdent && ident.Name == "nil" {
					method.resultText = "void"
				} else {
					method.result = pkg.TypesInfo.TypeOf(call.Args[1])
				}
				missing[method] = false
				return false
			})
			return false
		})
	}
}

func methodForExpression(pkg *packages.Package, methodObjects map[types.Object]*methodInfo, expr ast.Expr) *methodInfo {
	call, ok := expr.(*ast.CallExpr)
	if ok && len(call.Args) == 1 {
		expr = call.Args[0]
	}
	ident, ok := expr.(*ast.Ident)
	if !ok {
		return nil
	}
	return methodObjects[pkg.TypesInfo.Uses[ident]]
}

type typeRenderer struct {
	apiPackagePath     string
	queued             []*types.Named
	seen               map[*types.TypeName]bool
	names              map[string]*types.TypeName
	imports            map[string][]string
	docs               map[types.Object]string
	packages           map[string]*packages.Package
	documentIdentifier *types.TypeName
}

func newTypeRenderer(apiPackage *packages.Package) *typeRenderer {
	r := &typeRenderer{
		apiPackagePath: apiPackage.PkgPath,
		seen:           make(map[*types.TypeName]bool),
		names:          make(map[string]*types.TypeName),
		imports:        make(map[string][]string),
		docs:           make(map[types.Object]string),
		packages:       make(map[string]*packages.Package),
	}
	r.indexPackage(apiPackage)
	return r
}

func (r *typeRenderer) indexPackage(pkg *packages.Package) {
	if r.packages[pkg.PkgPath] != nil {
		return
	}
	r.packages[pkg.PkgPath] = pkg
	for _, imported := range pkg.Imports {
		r.indexPackage(imported)
	}
	for _, file := range pkg.Syntax {
		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok.String() != "type" {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec := spec.(*ast.TypeSpec)
				r.recordDoc(pkg.TypesInfo.Defs[typeSpec.Name], firstDoc(typeSpec.Doc, genDecl.Doc))
				structType, ok := typeSpec.Type.(*ast.StructType)
				if !ok {
					continue
				}
				for _, field := range structType.Fields.List {
					for _, name := range field.Names {
						r.recordDoc(pkg.TypesInfo.Defs[name], firstDoc(field.Doc, field.Comment))
					}
				}
			}
		}
	}
}

func (r *typeRenderer) recordDoc(obj types.Object, doc *ast.CommentGroup) {
	if obj != nil && doc != nil {
		r.docs[obj] = strings.TrimSpace(doc.Text())
	}
}

func firstDoc(docs ...*ast.CommentGroup) *ast.CommentGroup {
	for _, doc := range docs {
		if doc != nil {
			return doc
		}
	}
	return nil
}

func (r *typeRenderer) requestType(t types.Type) string {
	if pointer, ok := types.Unalias(t).(*types.Pointer); ok {
		t = pointer.Elem()
	}
	return r.typeString(t, false)
}

func (r *typeRenderer) resultType(t types.Type, nullable bool) string {
	if pointer, ok := types.Unalias(t).(*types.Pointer); ok {
		t = pointer.Elem()
	}
	result := r.typeString(t, false)
	if nullable {
		result += " | null"
	}
	return result
}

func (r *typeRenderer) typeString(t types.Type, allowNull bool) string {
	if t == nil {
		return "void"
	}
	t = types.Unalias(t)
	var result string
	switch t := t.(type) {
	case *types.Basic:
		result = basicType(t)
	case *types.Pointer:
		result = r.typeString(t.Elem(), false)
	case *types.Slice:
		result = arrayElement(r.typeString(t.Elem(), false)) + "[]"
	case *types.Array:
		result = arrayElement(r.typeString(t.Elem(), false)) + "[]"
	case *types.Map:
		result = fmt.Sprintf("Record<string, %s>", r.typeString(t.Elem(), true))
	case *types.Interface:
		result = "unknown"
	case *types.Struct:
		result = r.inlineStruct(t)
	case *types.Named:
		result = r.namedType(t)
	default:
		result = "unknown"
	}
	if allowNull && result != "unknown" {
		switch t.(type) {
		case *types.Pointer, *types.Slice, *types.Map:
			return result + " | null"
		}
	}
	return result
}

func basicType(t *types.Basic) string {
	switch {
	case t.Info()&types.IsBoolean != 0:
		return "boolean"
	case t.Info()&(types.IsInteger|types.IsFloat|types.IsComplex) != 0:
		return "number"
	case t.Info()&types.IsString != 0:
		return "string"
	case t.Kind() == types.UntypedNil:
		return "null"
	default:
		return "unknown"
	}
}

func (r *typeRenderer) namedType(named *types.Named) string {
	obj := named.Obj()
	if obj.Name() == "error" && obj.Pkg() == nil {
		return "string"
	}
	qualifiedName := obj.Pkg().Path() + "." + obj.Name()
	switch qualifiedName {
	case r.apiPackagePath + ".DocumentIdentifier":
		r.documentIdentifier = obj
		return "DocumentIdentifier"
	case "github.com/microsoft/TypeScript/tsc/internal/packagejson.JSONValue":
		return "unknown"
	case "github.com/microsoft/TypeScript/tsc/internal/json.Value":
		return "unknown"
	case "github.com/go-json-experiment/json/jsontext.Value": // multiple ways to refer to this type depending on `go` version
		return "unknown"
	case "encoding/json/jsontext.Value":
		return "unknown"
	case "github.com/microsoft/TypeScript/tsc/internal/core.Tristate":
		return "boolean"
	case "github.com/microsoft/TypeScript/tsc/internal/core.JsxEmit":
		return r.importType("JsxEmit", "#enums/jsxEmit")
	case "github.com/microsoft/TypeScript/tsc/internal/core.ModuleDetectionKind":
		return r.importType("ModuleDetectionKind", "#enums/moduleDetectionKind")
	case "github.com/microsoft/TypeScript/tsc/internal/core.ModuleKind":
		return r.importType("ModuleKind", "#enums/moduleKind")
	case "github.com/microsoft/TypeScript/tsc/internal/core.ModuleResolutionKind":
		return r.importType("ModuleResolutionKind", "#enums/moduleResolutionKind")
	case "github.com/microsoft/TypeScript/tsc/internal/core.NewLineKind":
		return r.importType("NewLineKind", "#enums/newLineKind")
	case "github.com/microsoft/TypeScript/tsc/internal/core.ScriptTarget":
		return r.importType("ScriptTarget", "#enums/scriptTarget")
	case "github.com/microsoft/TypeScript/tsc/internal/collections.OrderedMap":
		if named.TypeArgs().Len() != 2 {
			return "Record<string, unknown>"
		}
		return fmt.Sprintf("Record<string, %s>", r.typeString(named.TypeArgs().At(1), false))
	}
	if _, ok := named.Underlying().(*types.Struct); !ok {
		if literals := r.stringLiterals(named); len(literals) > 0 {
			return strings.Join(literals, " | ")
		}
		return r.typeString(named.Underlying(), false)
	}
	tsName := exportedName(obj.Name())
	if previous := r.names[tsName]; previous != nil && previous != obj {
		panic(fmt.Sprintf("TypeScript name collision between %s and %s", previous, obj))
	}
	r.names[tsName] = obj
	if !r.seen[obj] {
		r.seen[obj] = true
		r.queued = append(r.queued, named)
	}
	return tsName
}

func (r *typeRenderer) stringLiterals(named *types.Named) []string {
	if basic, ok := named.Underlying().(*types.Basic); !ok || basic.Info()&types.IsString == 0 {
		return nil
	}
	pkg := r.packages[named.Obj().Pkg().Path()]
	if pkg == nil {
		return nil
	}
	var literals []string
	for _, name := range pkg.Types.Scope().Names() {
		constantObject, ok := pkg.Types.Scope().Lookup(name).(*types.Const)
		if !ok || constantObject.Val().Kind() != constant.String || !types.Identical(constantObject.Type(), named) {
			continue
		}
		literal := strconv.Quote(constant.StringVal(constantObject.Val()))
		if !slices.Contains(literals, literal) {
			literals = append(literals, literal)
		}
	}
	sort.Strings(literals)
	return literals
}

func (r *typeRenderer) inlineStruct(structType *types.Struct) string {
	var fields []string
	multiline := false
	for i := range structType.NumFields() {
		field, include, optional, nonnil, deprecated, internal := jsonField(structType, i)
		if !include || deprecated || internal {
			continue
		}
		fieldType := r.typeString(structType.Field(i).Type(), !optional && !nonnil)
		doc := r.docs[structType.Field(i)]
		multiline = multiline || doc != ""
		fields = append(fields, fmt.Sprintf("%s%s%s: %s", inlineDoc(doc), propertyName(field), optionalMarker(optional), fieldType))
	}
	if len(fields) == 0 {
		return "Record<string, never>"
	}
	if multiline {
		return "{\n" + strings.Join(fields, ";\n") + ";\n}"
	}
	return "{ " + strings.Join(fields, "; ") + "; }"
}

func inlineDoc(doc string) string {
	if doc == "" {
		return ""
	}
	doc = strings.ReplaceAll(doc, "*/", "*\\/")
	return "/** " + jsDocLine(strings.Join(strings.Fields(doc), " ")) + " */\n"
}

func (r *typeRenderer) declarations() (string, error) {
	var out bytes.Buffer
	if strings.Contains(strings.Join(r.referencedNames(), ","), "DocumentIdentifier") {
		writeDoc(&out, "", r.docs[r.documentIdentifier])
		out.WriteString("export type DocumentIdentifier = string | { uri: string; };\n\n")
	}
	for len(r.queued) > 0 {
		named := r.queued[0]
		r.queued = r.queued[1:]
		structType := named.Underlying().(*types.Struct)
		isParams := strings.HasSuffix(named.Obj().Name(), "Params")
		writeDoc(&out, "", r.docs[named.Obj()])
		fmt.Fprintf(&out, "export interface %s {\n", exportedName(named.Obj().Name()))
		for i := range structType.NumFields() {
			field, include, optional, nonnil, deprecated, internal := jsonField(structType, i)
			if !include || deprecated || internal {
				continue
			}
			fieldType := r.typeString(structType.Field(i).Type(), !optional && !nonnil)
			if isParams && isArrayType(structType.Field(i).Type()) {
				fieldType = "readonly " + fieldType
			}
			writeDoc(&out, "    ", r.docs[structType.Field(i)])
			fmt.Fprintf(&out, "    %s%s: %s;\n", propertyName(field), optionalMarker(optional), fieldType)
		}
		out.WriteString("}\n\n")
	}
	return strings.TrimRight(out.String(), "\n") + "\n", nil
}

func writeDoc(out *bytes.Buffer, indent string, doc string) {
	if doc == "" {
		return
	}
	doc = strings.ReplaceAll(doc, "*/", "*\\/")
	lines := strings.Split(doc, "\n")
	if len(lines) == 1 {
		fmt.Fprintf(out, "%s/** %s */\n", indent, jsDocLine(lines[0]))
		return
	}
	fmt.Fprintf(out, "%s/**\n", indent)
	for _, line := range lines {
		fmt.Fprintf(out, "%s * %s\n", indent, jsDocLine(line))
	}
	fmt.Fprintf(out, "%s */\n", indent)
}

func jsDocLine(line string) string {
	if after, ok := strings.CutPrefix(line, "Deprecated:"); ok {
		return "@deprecated" + after
	}
	return line
}

func (r *typeRenderer) importDeclarations() string {
	var out bytes.Buffer
	paths := make([]string, 0, len(r.imports))
	for path := range r.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		names := r.imports[path]
		sort.Strings(names)
		fmt.Fprintf(&out, "import { %s } from %q;\n", strings.Join(names, ", "), path)
	}
	out.WriteString("\n")
	for _, path := range paths {
		fmt.Fprintf(&out, "export { %s } from %q;\n", strings.Join(r.imports[path], ", "), path)
	}
	return out.String()
}

func (r *typeRenderer) importType(name string, path string) string {
	if !slices.Contains(r.imports[path], name) {
		r.imports[path] = append(r.imports[path], name)
	}
	return name
}

func (r *typeRenderer) referencedNames() []string {
	names := make([]string, 0, len(r.names)+1)
	for name := range r.names {
		names = append(names, name)
	}
	// DocumentIdentifier is represented specially and is not in names.
	names = append(names, "DocumentIdentifier")
	sort.Strings(names)
	return names
}

func jsonField(structType *types.Struct, index int) (name string, include bool, optional bool, nonnil bool, deprecated bool, internal bool) {
	field := structType.Field(index)
	if !field.Exported() {
		return "", false, false, false, false, false
	}
	tag := reflect.StructTag(structType.Tag(index)).Get("json")
	noniltag := reflect.StructTag(structType.Tag(index)).Get("nonnil")
	deprecatedtag := reflect.StructTag(structType.Tag(index)).Get("deprecated")
	apitag := reflect.StructTag(structType.Tag(index)).Get("api")
	internaltag := reflect.StructTag(structType.Tag(index)).Get("internal")
	parts := strings.Split(tag, ",")
	name = parts[0]
	if name == "-" {
		return "", false, false, noniltag == "true", deprecatedtag == "true" && apitag != "true", internaltag == "true"
	}
	if name == "" {
		name = field.Name()
	}
	for _, option := range parts[1:] {
		if option == "omitempty" || option == "omitzero" {
			optional = true
		}
	}
	return name, true, optional, noniltag == "true", deprecatedtag == "true" && apitag != "true", internaltag == "true"
}

func exportedName(value string) string {
	if value == "" {
		return value
	}
	return strings.ToUpper(value[:1]) + value[1:]
}

func optionalMarker(optional bool) string {
	if optional {
		return "?"
	}
	return ""
}

func propertyName(name string) string {
	for i, char := range name {
		if (char >= 'a' && char <= 'z') || (char >= 'A' && char <= 'Z') || char == '_' || char == '$' || (i > 0 && char >= '0' && char <= '9') {
			continue
		}
		return strconv.Quote(name)
	}
	return name
}

func arrayElement(element string) string {
	if strings.Contains(element, " | ") {
		return "(" + element + ")"
	}
	return element
}

func isArrayType(t types.Type) bool {
	switch types.Unalias(t).(type) {
	case *types.Array, *types.Slice:
		return true
	default:
		return false
	}
}
