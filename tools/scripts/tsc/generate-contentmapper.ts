/**
 * Generates content mapper protocol and span map types from the JSON schema.
 * Usage: npx hereby generate:contentmapper [--force]
 */

import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { GeneratedFile } from "../gen/generatedFile.mts";
import {
    formatFilesSync,
    parseGeneratorArgs,
    repoRoot,
} from "../gen/utils.mts";

interface Schema {
    $ref?: string;
    type?: string | string[];
    description?: string;
    properties?: Record<string, Schema>;
    required?: string[];
    items?: Schema | Schema[];
    additionalItems?: Schema | boolean;
    anyOf?: Schema[];
    oneOf?: Schema[];
    allOf?: Schema[];
    const?: number;
    enum?: (string | number)[];
    minimum?: number;
    maximum?: number;
    minItems?: number;
    maxItems?: number;
    title?: string;
}

export interface SchemaDocument {
    "definitions": Record<string, Schema>;
    "x-methods": Record<string, { params: Schema; result: Schema; }>;
}

export const schemaFile = "packages/typescript/schemas/contentmapper.schema.json";
const schemaPath = path.join(repoRoot, schemaFile);
export const outputs = [
    "tsc/internal/contentmapper/protocol_generated.go",
    "tsc/internal/spanmap/types_generated.go",
    "packages/typescript/src/ast/spanMapTypes.generated.ts",
] as const;

const spanMapEnums = {
    SpanMapKind: "Kind",
    SpanMapFidelity: "Fidelity",
    SpanMapFeature: "Feature",
} as const;

const spanMapObjects = {
    SpanMapSourceSegment: { go: "Segment", ts: "SpanMapSegment" },
    SpanMapPosition: { go: "MappedPosition", ts: "MappedPosition" },
    SpanMapRange: { go: "MappedSpan", ts: "MappedRange" },
} as const;

const spanMapReferences: Record<string, { go: string; ts: string; }> = {
    ...Object.fromEntries(Object.entries(spanMapEnums).map(([name, go]) => [name, { go, ts: name }])),
    ...spanMapObjects,
    SpanMapOffset: { go: "core.TextPos", ts: "number" },
    SpanMapTextRange: { go: "core.TextRange", ts: "ReadonlyTextRange" },
};

const generatedHeader = "// Code generated by tools/scripts/tsc/generate-contentmapper.ts. DO NOT EDIT.";

export function readSchema(): SchemaDocument {
    return JSON.parse(fs.readFileSync(schemaPath, "utf8"));
}

export function spanMapEnumMembers(document: SchemaDocument, name: string): { name: string; value: string; description: string | undefined; }[] {
    const schema = document.definitions[name];
    assert(schema?.type === "integer", `Unsupported ${name} enum type`);
    const variants = schema.oneOf ?? schema.anyOf;
    assert(variants?.length, `Missing ${name} enum members`);
    const names = new Set<string>();
    const values = new Set<number>();
    const members = variants.flatMap(member => {
        if (member.const === undefined) {
            assert(
                schema.anyOf && !member.title
                    && member.minimum !== undefined && Number.isInteger(member.minimum) && member.minimum >= 0
                    && member.maximum !== undefined && Number.isInteger(member.maximum) && member.maximum <= 2147483647
                    && member.minimum <= member.maximum,
                `Unsupported ${name} enum variant`,
            );
            return [];
        }
        assert(member.title, `Missing ${name} enum member title`);
        goName(member.title);
        assert(!names.has(member.title), `Duplicate ${name} enum member title: ${member.title}`);
        assert(!values.has(member.const), `Duplicate ${name} enum member value: ${member.const}`);
        assert(Number.isInteger(member.const) && member.const >= -2147483648 && member.const <= 2147483647, `Unsupported ${name} enum value`);
        names.add(member.title);
        values.add(member.const);
        return [{ name: member.title, value: String(member.const), description: member.description }];
    });
    assert(members.length, `Missing ${name} enum members`);
    return members;
}

function spanMapTuple(document: SchemaDocument): Schema & { items: Schema[]; minItems: number; maxItems: number; } {
    const schema = document.definitions.SpanMapSegment;
    assert(schema.type === "array" && Array.isArray(schema.items), "Unsupported SpanMapSegment tuple");
    assert(schema.minItems === 5 && schema.maxItems === 6 && schema.items.length === 6, "Unsupported SpanMapSegment tuple length");
    assert(
        schema.items.every((item, index) =>
            item.title && (index < 4
                ? item.type === "integer" && item.minimum !== undefined && item.minimum >= -2147483648 && item.maximum !== undefined && item.maximum <= 2147483647
                : item.$ref === `#/definitions/${index === 4 ? "SpanMapKind" : "SpanMapFeature"}`)
        ),
        "Unsupported SpanMapSegment tuple items",
    );
    return { ...schema, items: schema.items, minItems: schema.minItems, maxItems: schema.maxItems };
}

function spanMapType(schema: Schema, document: SchemaDocument, language: "go" | "ts"): string {
    assert(schema.$ref, "Missing span map property reference");
    const name = referenceName(schema.$ref, document.definitions);
    const type = spanMapReferences[name];
    assert(type, `Unsupported span map reference: ${name}`);
    return type[language];
}

export function generateSpanMapGo(document: SchemaDocument): string {
    const lines = [generatedHeader, "", "package spanmap", "", 'import "github.com/microsoft/TypeScript/tsc/internal/core"', ""];
    for (const [name, type] of Object.entries(spanMapEnums)) {
        lines.push(...typeDescription(type, document.definitions[name].description), `type ${type} int32`, "", "const (");
        for (const member of spanMapEnumMembers(document, name)) {
            lines.push(...typeDescription(`${type}${member.name}`, member.description).map(line => `\t${line}`));
            lines.push(`\t${type}${member.name} ${type} = ${member.value}`);
        }
        lines.push(")", "");
    }
    const tuple = spanMapTuple(document);
    lines.push(...typeDescription("SegmentTuple", tuple.description), "type SegmentTuple []int32", "");
    for (const [name, types] of Object.entries(spanMapObjects)) {
        const schema = document.definitions[name];
        assert(schema.type === "object" && schema.properties, `Unsupported ${name} object`);
        lines.push(...typeDescription(types.go, schema.description), `type ${types.go} struct {`);
        for (const [property, value] of Object.entries(schema.properties)) {
            const field = name === "SpanMapRange" && property === "range" ? "Span" : goName(property);
            lines.push(`\t${field} ${spanMapType(value, document, "go")}`);
        }
        lines.push("}", "");
    }
    return lines.join("\n");
}

export function generateSpanMapTS(document: SchemaDocument): string {
    const lines = [
        generatedHeader,
        "",
        ...Object.keys(spanMapEnums).sort().map(name => `import type { ${name} } from "../../enums/${name[0].toLowerCase() + name.slice(1)}.js";`),
        'import type { ReadonlyTextRange } from "./ast.ts";',
        "",
    ];
    const tuple = spanMapTuple(document);
    const items = tuple.items.map((item, index) => {
        const type = item.$ref ? spanMapType(item, document, "ts") : "number";
        return `${item.title}${index >= tuple.minItems ? "?" : ""}: ${type}`;
    });
    lines.push(`/** ${tuple.description} */`, `export type SpanMapSegmentTuple = [${items.join(", ")}];`, "");
    for (const [name, types] of Object.entries(spanMapObjects)) {
        const schema = document.definitions[name];
        assert(schema.type === "object" && schema.properties, `Unsupported ${name} object`);
        const required = new Set(schema.required);
        lines.push(`/** ${schema.description} */`, `export interface ${types.ts} {`);
        for (const [property, value] of Object.entries(schema.properties)) {
            const optional = !required.has(property);
            lines.push(`    readonly ${property}${optional ? "?" : ""}: ${spanMapType(value, document, "ts")}${optional ? " | undefined" : ""};`);
        }
        lines.push("}", "");
    }
    return lines.join("\n");
}

const enumNames: Record<string, Record<string, string>> = {
    PositionEncoding: { "utf-8": "UTF8", "utf-16": "UTF16" },
    DiagnosticDirectivePolicy: { "0": "Ignore", "1": "Expect" },
};

function referenceName(ref: string, definitions: Record<string, Schema>): string {
    const match = /^#\/definitions\/([A-Za-z][A-Za-z0-9]*)$/.exec(ref);
    assert(match && definitions[match[1]], `Unsupported or missing schema reference: ${ref}`);
    return match[1];
}

function goName(name: string): string {
    assert(/^[a-zA-Z][a-zA-Z0-9]*$/.test(name), `Unsupported Go name: ${name}`);
    return name[0].toUpperCase() + name.slice(1);
}

function schemaType(schema: Schema): string | undefined {
    const type = schema.type;
    if (!Array.isArray(type)) return type;
    assert(type.length === 2 && type.includes("array") && type.includes("null"), `Unsupported schema type: ${type.join(", ")}`);
    return "array";
}

function goType(schema: Schema, definitions: Record<string, Schema>): string {
    if (schema.$ref) return referenceName(schema.$ref, definitions);
    const type = schemaType(schema);
    if (schema.anyOf || (!type && !schema.allOf)) return "json.Value";
    switch (type) {
        case "string":
            return "string";
        case "integer":
            return schema.minimum === -2147483648 && schema.maximum === 2147483647 ? "int32" : "int";
        case "array":
            assert(schema.items && !Array.isArray(schema.items), "Unsupported array items");
            return `[]${goType(schema.items, definitions)}`;
        default:
            throw new Error(`Unsupported schema type: ${type}`);
    }
}

function referencedDescription(schema: Schema, definitions: Record<string, Schema>): string | undefined {
    if (schema.description) return schema.description;
    return schema.$ref ? definitions[referenceName(schema.$ref, definitions)].description : undefined;
}

function nounPhrase(text: string): string {
    const phrase = text.trim().replace(/\s+/g, " ").replace(/^[A-Z](?=[a-z]|\s|$)/, first => first.toLowerCase());
    return /^(?:a|an|the|this|these|those|some|all|no)\b/.test(phrase) ? phrase : `the ${phrase}`;
}

function fieldDescription(name: string, schema: Schema, definitions: Record<string, Schema>): string[] {
    const text = referencedDescription(schema, definitions);
    if (!text) return [];
    const target = schema.$ref ? definitions[referenceName(schema.$ref, definitions)] : schema;
    const type = schemaType(target);
    const verb = type === "array" ? "lists" : !type || type === "object" ? "contains" : "is";
    return [`// ${name} ${verb} ${nounPhrase(text)}`];
}

function mappedDiagnosticDirectiveVariants(schema: Schema): { ignore: Schema; expect: Schema; expectMaxItems: number; } {
    assert(schema.oneOf?.length === 2, "MappedDiagnosticDirective must have two policy variants");
    const variants = new Map<number, Schema>();
    for (const variant of schema.oneOf) {
        const items = variant.items;
        if (!Array.isArray(items)) throw new Error("Unsupported MappedDiagnosticDirective policy variant");
        assert(
            variant.type === "array" && items.length >= 5
                && variant.minItems === 5 && items[4].title === "policy"
                && (items[4].const === 0 || items[4].const === 1),
            "Unsupported MappedDiagnosticDirective policy variant",
        );
        assert(!variants.has(items[4].const), "Duplicate MappedDiagnosticDirective policy variant");
        variants.set(items[4].const, variant);
    }
    const ignore = variants.get(0);
    const expect = variants.get(1);
    assert(ignore && expect, "MappedDiagnosticDirective must define ignore and expect variants");
    assert(
        typeof ignore.additionalItems === "object" && ignore.additionalItems.type === "integer"
            && ignore.additionalItems.minimum === 1 && ignore.additionalItems.maximum === 2147483647
            && ignore.maxItems === undefined,
        "Unsupported MappedDiagnosticDirective ignore variant",
    );
    const expectItems = expect.items;
    const expectMaxItems = expect.maxItems;
    if (!Array.isArray(expectItems)) throw new Error("Unsupported MappedDiagnosticDirective expect variant");
    assert(
        expectItems.length === 6 && expectItems[5].title === "unusedExpectDirectiveIndex"
            && expectItems[5].type === "integer" && expectItems[5].minimum === 0
            && expectMaxItems === 6,
        "Unsupported MappedDiagnosticDirective expect variant",
    );
    for (const variant of [ignore, expect]) {
        const items = variant.items;
        assert(Array.isArray(items), "Unsupported MappedDiagnosticDirective tuple items");
        assert(
            items.slice(0, 4).every((item, index) =>
                item.title === ["originalStart", "originalLength", "virtualStart", "virtualEnd"][index]
                && item.type === "integer"
                && JSON.stringify(item) === JSON.stringify(expectItems[index])
            ),
            "MappedDiagnosticDirective policy variants must share range fields",
        );
        assert(variant.description, "Missing MappedDiagnosticDirective policy variant description");
    }
    return { ignore, expect, expectMaxItems };
}

function typeDescription(name: string, text: string | undefined): string[] {
    if (!text) return [];
    const normalized = text.trim().replace(/\s+/g, " ");
    return commentLines(`${name} ${normalized.startsWith("[") ? `is encoded as ${normalized}` : `describes ${nounPhrase(normalized)}`}`);
}

function commentLines(description: string): string[] {
    const lines: string[] = [];
    let line = "//";
    for (const word of description.split(" ")) {
        if (line.length > 2 && line.length + 1 + word.length > 120) {
            lines.push(line);
            line = "//";
        }
        line += ` ${word}`;
    }
    lines.push(line);
    return lines;
}

export function generateContentMapper(document: SchemaDocument): string {
    const definitions = document.definitions;
    assert(definitions && typeof definitions === "object", "Missing schema definitions");
    const methods = document["x-methods"];
    assert(methods && typeof methods === "object" && Object.keys(methods).length > 0, "Missing content mapper methods");
    const lines = [
        generatedHeader,
        "",
        "package contentmapper",
        "",
        "import (",
        '\t"fmt"',
        '\t"github.com/microsoft/TypeScript/tsc/internal/json"',
        '\t"github.com/microsoft/TypeScript/tsc/internal/spanmap"',
        ")",
        "",
        "// Content mapper protocol method names.",
        "const (",
    ];
    const methodIdentifiers = new Set<string>();
    for (const [method, definition] of Object.entries(methods)) {
        const identifier = `Method${goName(method)}`;
        assert(!methodIdentifiers.has(identifier), `Duplicate content mapper method identifier: ${identifier}`);
        methodIdentifiers.add(identifier);
        assert(definition.params?.$ref, `Missing params schema for content mapper method: ${method}`);
        referenceName(definition.params.$ref, definitions);
        if (definition.result?.$ref) {
            referenceName(definition.result.$ref, definitions);
        }
        else {
            assert(definition.result?.type === "null", `Unsupported result schema for content mapper method: ${method}`);
        }
        lines.push(`\t${identifier} = ${JSON.stringify(method)}`);
    }
    lines.push(")", "");

    function objectFields(name: string, schema: Schema): void {
        assert(schema.type === "object" && schema.properties, `Unsupported object: ${name}`);
        const required = new Set(schema.required ?? []);
        for (const property of required) assert(property in schema.properties, `Unknown required property ${name}.${property}`);
        for (const [property, value] of Object.entries(schema.properties)) {
            const field = goName(property);
            let type = goType(value, definitions);
            if (!required.has(property) && value.$ref && definitions[referenceName(value.$ref, definitions)].type === "object") {
                type = `*${type}`;
            }
            // Preserve the existing wire representation even though the schema makes this optional.
            const optional = !required.has(property) && !(name === "OpenProjectResult" && property === "configIdentity");
            lines.push(...fieldDescription(field, value, definitions).map(line => `\t${line}`));
            lines.push(`\t${field} ${type} \`json:"${property}${optional ? ",omitempty" : ""}"\``);
        }
    }

    for (const [name, schema] of Object.entries(definitions)) {
        if (Object.hasOwn(spanMapReferences, name)) continue;
        goName(name);
        lines.push(...typeDescription(name, schema.description));
        if (schema.$ref) {
            const ref = referenceName(schema.$ref, definitions);
            assert(definitions[ref].type === "object", `Unsupported definition reference: ${name}`);
            lines.push(`type ${name} struct {`, `\t${ref}`, "}");
        }
        else if (schema.allOf) {
            lines.push(`type ${name} struct {`);
            for (const part of schema.allOf) {
                if (part.$ref) {
                    const ref = referenceName(part.$ref, definitions);
                    assert(definitions[ref].type === "object", `Unsupported allOf reference: ${name}`);
                    lines.push(`\t${ref}`);
                }
                else {
                    objectFields(name, part);
                }
            }
            lines.push("}");
        }
        else if (schema.type === "object") {
            lines.push(`type ${name} struct {`);
            objectFields(name, schema);
            lines.push("}");
        }
        else if (schema.enum) {
            const names = enumNames[name];
            assert(names && schema.enum.length === Object.keys(names).length && schema.enum.every(value => Object.hasOwn(names, String(value))), `Unsupported ${name} enum`);
            assert(schema.type === "string" || schema.type === "integer", `Unsupported ${name} enum type`);
            lines.push(`type ${name} ${schema.type === "string" ? "string" : "uint8"}`, "", "const (");
            for (const value of schema.enum) lines.push(`\t${name}${names[String(value)]} ${name} = ${JSON.stringify(value)}`);
            lines.push(")");
        }
        else if (name === "MappedDiagnosticDirective" && schema.oneOf) {
            const { ignore, expect, expectMaxItems } = mappedDiagnosticDirectiveVariants(schema);
            assert(schema.title, "Missing MappedDiagnosticDirective title");
            const ignoreItems = ignore.items as Schema[];
            const expectItems = expect.items as Schema[];
            const policyNames = enumNames.DiagnosticDirectivePolicy;
            const ignorePolicy = `DiagnosticDirectivePolicy${policyNames[String(ignoreItems[4].const)]}`;
            const expectPolicy = `DiagnosticDirectivePolicy${policyNames[String(expectItems[4].const)]}`;
            const fields = expectItems.slice(0, 4);
            assert(
                fields.every((field, index) => field.title === ["originalStart", "originalLength", "virtualStart", "virtualEnd"][index]),
                "Unsupported MappedDiagnosticDirective fields",
            );
            for (const [policy, variant] of [[ignorePolicy, ignore], [expectPolicy, expect]] as const) {
                const description = variant.description!.trim().replace(/\s+/g, " ");
                lines.push("//", ...commentLines(`${policy} encodes ${/^[aeiou]/i.test(description) ? "an" : "a"} ${nounPhrase(description).replace(/^the /, "")}`));
            }
            lines.push("type MappedDiagnosticDirective struct {");
            for (const field of fields) {
                const name = goName(field.title!);
                lines.push(...fieldDescription(name, field, definitions).map(line => `\t${line}`));
                lines.push(`\t${name} ${goType(field, definitions)}`);
            }
            lines.push(
                "\t// Policy is the diagnostic directive policy: 0 ignores diagnostics; 1 expects a diagnostic.",
                "\tPolicy DiagnosticDirectivePolicy",
                "\t// UnusedExpectDirectiveIndex selects the unused diagnostic for an expect directive.",
                "\tUnusedExpectDirectiveIndex *int",
                "\t// DiagnosticCodes selects TypeScript diagnostic codes for an ignore directive; empty selects all codes.",
                "\tDiagnosticCodes []int32",
                "}",
                "",
                "var (",
                "\t_ json.MarshalerTo     = MappedDiagnosticDirective{}",
                "\t_ json.UnmarshalerFrom = (*MappedDiagnosticDirective)(nil)",
                ")",
                "",
                "func (d MappedDiagnosticDirective) MarshalJSONTo(enc *json.Encoder) error {",
                "\ttuple := []any{d.OriginalStart, d.OriginalLength, d.VirtualStart, d.VirtualEnd, d.Policy}",
                `\tswitch d.Policy {`,
                `\tcase ${ignorePolicy}:`,
                "\t\tfor _, code := range d.DiagnosticCodes {",
                "\t\t\ttuple = append(tuple, code)",
                "\t\t}",
                `\tcase ${expectPolicy}:`,
                "\t\tif d.UnusedExpectDirectiveIndex != nil {",
                "\t\t\ttuple = append(tuple, *d.UnusedExpectDirectiveIndex)",
                "\t\t}",
                "\t}",
                "\treturn json.MarshalEncode(enc, tuple)",
                "}",
                "",
                "func (d *MappedDiagnosticDirective) UnmarshalJSONFrom(dec *json.Decoder) error {",
                "\tvar tuple []json.Value",
                "\tif err := json.UnmarshalDecode(dec, &tuple); err != nil {",
                "\t\treturn err",
                "\t}",
                `\tif len(tuple) < ${ignore.minItems} {`,
                `\t\treturn fmt.Errorf("diagnostic directive tuple must contain at least ${ignore.minItems} elements, got %d", len(tuple))`,
                "\t}",
                "\t*d = MappedDiagnosticDirective{}",
                "\tfields := []any{&d.OriginalStart, &d.OriginalLength, &d.VirtualStart, &d.VirtualEnd, &d.Policy}",
                "\tfor i, field := range fields {",
                "\t\tif err := json.Unmarshal(tuple[i], field); err != nil {",
                '\t\t\treturn fmt.Errorf("invalid diagnostic directive tuple element %d: %w", i, err)',
                "\t\t}",
                "\t}",
                "\tswitch d.Policy {",
                `\tcase ${ignorePolicy}:`,
                `\t\tif len(tuple) > ${ignore.minItems} {`,
                `\t\t\td.DiagnosticCodes = make([]int32, len(tuple)-${ignore.minItems})`,
                "\t\t\tfor i := range d.DiagnosticCodes {",
                `\t\t\t\tif err := json.Unmarshal(tuple[i+${ignore.minItems}], &d.DiagnosticCodes[i]); err != nil {`,
                `\t\t\t\t\treturn fmt.Errorf("invalid diagnostic directive tuple element %d: %w", i+${ignore.minItems}, err)`,
                "\t\t\t\t}",
                "\t\t\t}",
                "\t\t}",
                `\tcase ${expectPolicy}:`,
                `\t\tif len(tuple) > ${expectMaxItems} {`,
                `\t\t\treturn fmt.Errorf("expect diagnostic directive tuple must contain at most ${expectMaxItems} elements, got %d", len(tuple))`,
                "\t\t}",
                `\t\tif len(tuple) == ${expectMaxItems} {`,
                "\t\t\td.UnusedExpectDirectiveIndex = new(int)",
                `\t\t\tif err := json.Unmarshal(tuple[${expectMaxItems - 1}], d.UnusedExpectDirectiveIndex); err != nil {`,
                `\t\t\t\treturn fmt.Errorf("invalid diagnostic directive tuple element ${expectMaxItems - 1}: %w", err)`,
                "\t\t\t}",
                "\t\t}",
                "\tdefault:",
                "\t\tif len(tuple) > 5 {",
                '\t\t\treturn fmt.Errorf("invalid diagnostic directive policy %d with additional tuple elements", d.Policy)',
                "\t\t}",
                "\t}",
                "\treturn nil",
                "}",
            );
        }
        else if (name === "SpanMapSegment") {
            spanMapTuple(document);
            lines.push(`type ${name} = spanmap.SegmentTuple`);
        }
        else {
            throw new Error(`Unsupported definition: ${name}`);
        }
        lines.push("");
    }
    return lines.join("\n");
}

export default function generate(force = false): void {
    const document = readSchema();
    const generators = [generateContentMapper, generateSpanMapGo, generateSpanMapTS];
    for (const [index, file] of outputs.entries()) {
        const output = new GeneratedFile(path.join(repoRoot, file), [import.meta.filename, schemaPath]);
        if (output.isCurrent(force)) continue;
        output.write(generators[index](document));
        formatFilesSync([output.fileName]);
        output.markCurrent();
        console.log(`Wrote ${output.fileName}`);
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    generate(parseGeneratorArgs({}).force);
}
