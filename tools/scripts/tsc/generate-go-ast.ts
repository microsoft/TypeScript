/**
 * Verifies that the generated Go structs do not embed a base along more than one path.
 */
function verifyNoDuplicateBases(): void {
    const problems: string[] = [];
    const check = (name: string, goExtends: string[]) => {
        const copies = new Map<string, number>();
        const walk = (keys: string[]) => {
            for (const key of keys) {
                copies.set(key, (copies.get(key) ?? 0) + 1);
                walk(baseGoEmbeds(api.getBase(key)));
            }
        };
        walk(goExtends);
        for (const [base, count] of copies) {
            if (count > 1) problems.push(`${name} inherits ${base} ${count} times`);
        }
    };
    for (const base of api.bases()) check(base.key, baseGoEmbeds(base));
    for (const node of api.nodes()) check(node.name, goEmbeds(node.extendsKeys));

    if (problems.length > 0) {
        throw new Error(`ast.json declares duplicate embedded bases:\n  ${problems.sort().join("\n  ")}`);
    }
}

/**
 * Verifies that the inheritance path containing NodeBase is embedded first.
 */
function verifyNodeBaseAtOffsetZero(): void {
    const containsNodeBase = (key: string): boolean => {
        if (key === "NodeBase") return true;
        return baseGoEmbeds(api.getBase(key)).some(containsNodeBase);
    };
    const problems: string[] = [];
    const check = (name: string, goExtends: string[], requireNodeBase: boolean) => {
        const nodeBaseIndex = goExtends.findIndex(containsNodeBase);
        if (nodeBaseIndex < 0 && requireNodeBase) {
            problems.push(`${name} does not embed NodeBase`);
        }
        else if (nodeBaseIndex > 0) {
            const preceding = goExtends.slice(0, nodeBaseIndex).filter(key => !isZeroSizeBase(key));
            if (preceding.length > 0) {
                problems.push(`${name} embeds ${goExtends[nodeBaseIndex]} after ${preceding.join(", ")}`);
            }
        }
    };
    for (const base of api.bases()) check(base.key, baseGoEmbeds(base), false);
    for (const node of api.nodes()) check(node.name, goEmbeds(node.extendsKeys), true);

    if (problems.length > 0) {
        throw new Error(`ast.json does not embed NodeBase at offset zero:\n  ${problems.sort().join("\n  ")}`);
    }
}

verifyNoDuplicateBases();
verifyNodeBaseAtOffsetZero();

// A base generated without fields or embeddings is a struct{} marker. Go pads a struct whose last field is
// zero-size (so the field's address stays in bounds), so markers are embedded first, never last; being
// zero-size, they don't move NodeBase off offset zero.
function isZeroSizeBase(key: string): boolean {
    const base = api.getBase(key);
    return !!base && base.fields.length === 0 && (base.extendsKeys.length === 0 || isInheritedDeclarationMarker(base));
}

function isInheritedDeclarationMarker(base: NodeType | undefined): boolean {
    return !!base &&
        base.fields.length === 0 &&
        base.extendsKeys.length === 1 &&
        base.extendsKeys[0] === "DeclarationBase";
}

function baseGoEmbeds(base: NodeType | undefined): string[] {
    return base && !isInheritedDeclarationMarker(base) ? goEmbeds(base.extendsKeys) : [];
}

function expandGoExtends(extendsKeys: string[]): string[] {
    const result: string[] = [];
    const seen = new Set<string>();
    for (const key of extendsKeys) {
        const base = api.getBase(key);
        // Go cannot embed multiple category bases that share DeclarationBase without
        // introducing ambiguous promoted fields and methods. Keep each empty category
        // marker and flatten its inherited storage alongside it.
        const keys = isInheritedDeclarationMarker(base) ? [key, ...(base?.extendsKeys ?? [])] : [key];
        for (const expanded of keys) {
            if (!seen.has(expanded)) {
                seen.add(expanded);
                result.push(expanded);
            }
        }
    }
    return result;
}

function goEmbeds(extendsKeys: string[]): string[] {
    const zeroSized: string[] = [];
    const nonZeroSized: string[] = [];
    for (const key of expandGoExtends(extendsKeys)) {
        if (isZeroSizeBase(key)) {
            zeroSized.push(key);
        }
        else {
            nonZeroSized.push(key);
        }
    }
    return [...zeroSized, ...nonZeroSized];
}

function nodeOwnFields(node: NodeType): MemberInfo[] {
    return node.members.filter(m => !m.inherited && !m.isKindParam() && !m.noGo);
}

function memberGoType(m: MemberInfo): string {
    return m.goOnly ? m.rawType as string : m.type.formatGoReference();
}

// Whether a field holds a single node handle, which records store as a nodeRef.
function isNodeField(f: { goOnly?: boolean; rawType: string | string[]; type: Type; }): boolean {
    if (f.goOnly) return f.rawType === "Node";
    const goType = f.type.formatGoReference();
    return f.type.baseKind() === "node" && !goType.startsWith("*") && !goType.startsWith("[]");
}

// Fields holding Go pointers are kept out of records, in the store's side
// table for their type, so that records contain no pointers.
const sideTables: Record<string, string> = {
    "*Symbol": "symbols",
    "*FlowNode": "flowNodes",
    "SymbolTable": "symbolTables",
    "*NodeList": "nodeLists",
    "*ModifierList": "modifierLists",
    "string": "texts",
    "[]string": "stringLists",
    "[]Node": "nodeSlices",
    "any": "values",
};

function sideTableOf(goType: string): string | undefined {
    if (Object.hasOwn(sideTables, goType)) return sideTables[goType];
    // Aliases of NodeList, such as *StatementList.
    if (/^\*\w+List$/.test(goType) && goType !== "*FlowList") return "nodeLists";
    return undefined;
}

function zeroCheck(goType: string, value: string): string {
    return goType === "string" ? `${value} == ""` : `${value} == nil`;
}

// The Go type a field has within a record.
function recordGoType(isNode: boolean, goType: string): string {
    if (isNode) return "nodeRef";
    if (goType === "string") return "textRef";
    return sideTableOf(goType) ? "sideRef" : goType;
}

function baseGoFields(key: string): GoField[] {
    const base = api.getBase(key);
    if (!base || HAND_WRITTEN_BASES.has(key)) return [];
    const fields: GoField[] = [];
    for (const ext of baseGoEmbeds(base)) fields.push(...baseGoFields(ext));
    for (const field of base.fields) {
        if (field.noGo) continue;
        fields.push({ name: field.name, goType: field.goOnly ? field.rawType as string : field.type.formatGoReference(), isNode: isNodeField(field) });
    }
    return fields;
}

function nodeGoFields(node: NodeType): GoField[] {
    const fields: GoField[] = [];
    for (const ext of goEmbeds(node.extendsKeys)) fields.push(...baseGoFields(ext));
    for (const m of nodeOwnFields(node)) fields.push({ name: m.name, goType: memberGoType(m), isNode: isNodeField(m) });
    return fields;
}

function generateStructDef(w: CodeWriter, node: NodeType) {
    const structName = node.name;
    w.write(`type ${dataName(node)} struct {`);
    w.push();

    // Embeddings from extends (each maps to a Go struct via convention)
    for (const ext of goEmbeds(node.extendsKeys)) {
        w.write(baseDataName(ext));
    }

    // Fields from members (skip inherited, Kind params, and noGo)
    for (const m of nodeOwnFields(node)) {
        const fieldName = goStorageName(m.name);
        const goType = recordGoType(isNodeField(m), memberGoType(m));
        const comment = buildFieldComment(m, goType !== memberGoType(m) ? memberGoType(m) : undefined);
        if (comment) {
            w.write(`${fieldName} ${goType} ${comment}`);
        }
        else {
            w.write(`${fieldName} ${goType}`);
        }
    }

    w.pop();
    w.write("}");
    w.write("");
    w.write(`type ${structName} struct{ Node }`);
    w.write("");
    w.write(`func (node ${structName}) data() *${dataName(node)} { return ${dataOf(node, "node")} }`);
    w.write("");
    generateFieldAccessors(w, structName, nodeGoFields(node), "node.data()");
}

function buildFieldComment(m: MemberInfo, refType?: string): string {
    const parts: string[] = [];
    if (refType) parts.push(refType);
    if (m.optional) parts.push("Optional");
    if (parts.length > 0) return `// ${parts.join(". ")}`;
    return "";
}

function goSubtreeFactsTerm(m: MemberInfo): string {
    const access = fieldAccess(m);
    if (m.listKind === "ModifierList") {
        return `propagateModifierListSubtreeFacts(${access})`;
    }
    if (m.type.kind === "list") {
        return `propagateNodeListSubtreeFacts(${access}, propagateSubtreeFacts)`;
    }
    return `propagateSubtreeFacts(${access})`;
}

function generateSubtreeFacts(w: CodeWriter, node: NodeType) {
    if (!node.generateSubtreeFacts) return;

    const childMembers = schemaMembers(node).filter(m => m.isChild());
    const structName = node.name;
    w.write(`func (node ${structName}) computeSubtreeFacts() SubtreeFacts {`);
    w.push();
    if (childMembers.length === 0) {
        w.write("return SubtreeFactsNone");
    }
    else {
        for (let index = 0; index < childMembers.length; index++) {
            const term = goSubtreeFactsTerm(childMembers[index]);
            if (index === 0) {
                const suffix = childMembers.length > 1 ? " |" : "";
                w.write(`return ${term}${suffix}`);
            }
            else {
                const suffix = index < childMembers.length - 1 ? " |" : "";
                w.write(`${term}${suffix}`);
            }
        }
    }
    w.pop();
    w.write("}");
    w.write("");
}

// ── Generate base struct definitions ──────────────────────────────────────

// Bases that are hand-written and should not be generated
const HAND_WRITTEN_BASES = new Set(["NodeBase"]);

function generateBaseStructDefs(w: CodeWriter) {
    w.write("// ──────────────────────────────────────────────────────────────────────");
    w.write("// Base struct definitions");
    w.write("// ──────────────────────────────────────────────────────────────────────");
    w.write("");

    for (const base of api.bases()) {
        if (HAND_WRITTEN_BASES.has(base.key)) continue;

        const structName = base.key;

        const goExts = baseGoEmbeds(base);

        w.write(`type ${baseDataName(structName)} struct {`);
        w.push();

        // Embeddings from extends
        for (const ext of goExts) {
            w.write(baseDataName(ext));
        }

        // Schema fields
        for (const field of base.fields) {
            if (field.noGo) continue;
            const valueType = field.goOnly ? field.rawType as string : field.type.formatGoReference();
            const goType = recordGoType(isNodeField(field), valueType);
            const parts = [];
            if (goType !== valueType) parts.push(valueType);
            if (field.optional) parts.push("Optional");
            const comment = parts.length > 0 ? ` // ${parts.join(". ")}` : "";
            w.write(`${goStorageName(field.name)} ${goType}${comment}`);
        }

        w.pop();
        w.write("}");
        w.write("");

        // Base views see the fields of whichever concrete node they wrap.
        w.write(`type ${structName} struct{ Node }`);
        w.write("");
        const fields = baseGoFields(structName);
        if (fields.length > 0) {
            generateBaseDataDispatch(w, base);
            generateFieldAccessors(w, structName, fields, `node.${baseDataName(structName)}()`);
        }
    }
}

function generateBaseDataDispatch(w: CodeWriter, base: NodeType) {
    const cases: { node: NodeType; kinds: string[]; }[] = [];
    for (const node of api.nodes()) {
        if (!transitiveBaseKeys(node).has(base.key)) continue;
        const kinds = node.allKinds().map(kind => kind.formatGoConstant());
        if (kinds.length !== 0) cases.push({ node, kinds });
    }
    const table = `${baseDataName(base.key)}Dispatch`;
    w.write(`var ${table} = [kindFlowReduceLabelData + 1]uint8{`);
    w.push();
    for (const [index, { kinds }] of cases.entries()) {
        for (const kind of kinds) {
            w.write(`${kind}: ${index + 1},`);
        }
    }
    w.pop();
    w.write("}");
    w.write("");
    w.write(`func (n Node) ${baseDataName(base.key)}() *${baseDataName(base.key)} {`);
    w.push();
    w.write(`switch ${table}[n.Kind()] {`);
    for (const [index, { node }] of cases.entries()) {
        w.write(`case ${index + 1}:`);
        w.push();
        w.write(`return &${dataOf(node, "n")}.${baseDataName(base.key)}`);
        w.pop();
    }
    w.write("}");
    w.write("return nil");
    w.pop();
    w.write("}");
    w.write("");
}

// ── Generate record layouts ────────────────────────────────────────────────

// Synthetic nodes declared by hand in flow.go, each with its own pseudo-kind.
const EXTRA_LAYOUTS = ["FlowSwitchClauseData", "FlowReduceLabelData"];

function layoutName(node: NodeType): string {
    return `layout${node.name}`;
}

function generateLayouts(w: CodeWriter) {
    w.write("// ──────────────────────────────────────────────────────────────────────");
    w.write("// Record layouts");
    w.write("// ──────────────────────────────────────────────────────────────────────");
    w.write("");
    w.write("// nodeLayout identifies the record table holding a node's fields.");
    w.write("type nodeLayout uint8");
    w.write("");
    w.write("const (");
    w.push();
    w.write("layoutNone nodeLayout = iota");
    for (const node of api.nodes()) w.write(layoutName(node));
    for (const name of EXTRA_LAYOUTS) w.write(`layout${name}`);
    w.write("layoutCount");
    w.pop();
    w.write(")");
    w.write("");
    w.write("var kindLayout = [kindFlowReduceLabelData + 1]nodeLayout{");
    w.push();
    for (const [node, kinds] of canonicalNodesByKind()) {
        for (const kind of kinds) w.write(`${kind}: ${layoutName(node)},`);
    }
    for (const name of EXTRA_LAYOUTS) w.write(`kind${name}: layout${name},`);
    w.pop();
    w.write("}");
    w.write("");
    w.write("// Every record must begin with its nodeBaseData header.");
    w.write("const (");
    w.push();
    for (const node of api.nodes()) w.write(`_ = -unsafe.Offsetof(${dataName(node)}{}.nodeBaseData)`);
    for (const name of EXTRA_LAYOUTS) w.write(`_ = -unsafe.Offsetof(${name[0].toLowerCase()}${name.slice(1)}{}.nodeBaseData)`);
    w.pop();
    w.write(")");
    w.write("");
    w.write("// allocRecords allocates n zeroed records of layout.");
    w.write("func allocRecords(layout nodeLayout, n int) unsafe.Pointer {");
    w.push();
    w.write("switch layout {");
    for (const node of api.nodes()) {
        w.write(`case ${layoutName(node)}:`);
        w.write(`return unsafe.Pointer(unsafe.SliceData(make([]${dataName(node)}, n)))`);
    }
    for (const name of EXTRA_LAYOUTS) {
        w.write(`case layout${name}:`);
        w.write(`return unsafe.Pointer(unsafe.SliceData(make([]${name[0].toLowerCase()}${name.slice(1)}, n)))`);
    }
    w.write("}");
    w.write(`panic("unknown node layout")`);
    w.pop();
    w.write("}");
    w.write("");
    w.write("// layoutRecord returns a zero record of layout.");
    w.write("func layoutRecord(layout nodeLayout) any {");
    w.push();
    w.write("switch layout {");
    for (const node of api.nodes()) {
        w.write(`case ${layoutName(node)}:`);
        w.write(`return ${dataName(node)}{}`);
    }
    for (const name of EXTRA_LAYOUTS) {
        w.write(`case layout${name}:`);
        w.write(`return ${name[0].toLowerCase()}${name.slice(1)}{}`);
    }
    w.write("}");
    w.write("return nil");
    w.pop();
    w.write("}");
    w.write("");
}

// ── Generate As*() cast methods ────────────────────────────────────────────

function generateKindCheck(w: CodeWriter, node: NodeType, expression: string, message: string) {
    const kinds = canonicalNodesByKind().get(node) ?? [];
    if (kinds.length === 1) {
        w.write(`if ${expression} != ${kinds[0]} {`);
        w.push();
        w.write(`panic("${message}")`);
        w.pop();
        w.write("}");
    }
    else {
        w.write(`switch ${expression} {`);
        w.write(`case ${kinds.join(", ")}:`);
        w.write("default:");
        w.push();
        w.write(`panic("${message}")`);
        w.pop();
        w.write("}");
    }
}

function generateAsCast(w: CodeWriter, node: NodeType) {
    const structName = node.name;
    const ret = node.handWritten ? `*${structName}` : structName;
    w.write(`func (n Node) As${structName}() ${ret} {`);
    w.push();
    generateKindCheck(w, node, "n.Kind()", `Invalid node cast to ${structName}`);
    w.write(`return ${viewOf(node, "n")}`);
    w.pop();
    w.write("}");
    w.write("");
}

