export function goValue(value: GoValue | { go: string; }): string {
    return typeof value === "object" ? value.go : JSON.stringify(value);
}

export function compilerDeclarations(model = options) {
    return model.compilerOptions.flatMap(option =>
        (option.declarations ?? []).map(declaration => ({
            name: option.name,
            kind: optionKind(option),
            ...declaration,
        }))
    );
}

function orderByName<T extends { name: string; }>(items: T[], order: string[], group: string): T[] {
    const names = new Set(items.map(item => item.name));
    const orderedNames = new Set(order);
    assert.equal(orderedNames.size, order.length, `Duplicate option in ${group} order`);
    for (const name of order) {
        assert(names.has(name), `Unknown option in ${group} order: ${name}`);
    }
    const missing = [...names].filter(name => !orderedNames.has(name));
    assert.equal(missing.length, 0, `Missing options in ${group} order: ${missing.join(", ")}`);
    return order.flatMap(name => items.filter(item => item.name === name));
}

export function validateOptions(model: OptionsModel): void {
    const constants = new Set<string>();
    const enumNames = new Set<string>();
    for (const enumDef of model.enums) {
        assert(!enumNames.has(enumDef.name), `Duplicate enum: ${enumDef.name}`);
        enumNames.add(enumDef.name);
        for (const member of enumDef.members) {
            const constant = `core.${enumDef.name}${member.name}`;
            assert(!constants.has(constant), `Duplicate enum member: ${constant}`);
            if (typeof member.value === "string") {
                assert(constants.has(`core.${enumDef.name}${member.value}`), `Unknown enum alias: ${constant}`);
            }
            else assert(Number.isInteger(member.value), `Invalid enum value: ${constant}`);
            constants.add(constant);
        }
    }
    const names = new Set<string>();
    const fields = new Set<string>();
    for (const option of model.compilerOptions) {
        for (const name of [option.name, ...(option.parseAliases ?? [])]) {
            assert(!names.has(name.toLowerCase()), `Duplicate compiler option: ${name}`);
            names.add(name.toLowerCase());
        }
        assert(!fields.has(fieldName(option)), `Duplicate compiler field: ${fieldName(option)}`);
        fields.add(fieldName(option));
        if (optionKind(option) === "Enum") assert(enumNames.has(option.type), `Unknown enum type: ${option.type}`);
        if (option.jsconfigDefault !== undefined) {
            const expected = option.type === "Tristate" ? "boolean" : option.type === "*int" ? "number" : "string";
            assert.equal(typeof option.jsconfigDefault, expected, `Invalid jsconfig default: ${option.name}`);
        }
    }
    for (const group of [model.watchOptions, model.typeAcquisition, model.buildOptions]) {
        const fields = group.flatMap(option => option.field ? [option.field.name] : []);
        assert.equal(new Set(fields).size, fields.length, "Duplicate stored option field");
        for (const option of group) {
            if (option.field) assert.equal(optionKind({ name: option.name, type: option.field.type }), option.kind, `Mismatched field type: ${option.name}`);
        }
    }
    const compiler = compilerDeclarations(model);
    for (const group of ["commonOptionsWithBuild", "optionsForCompiler"] as const) {
        orderByName(compiler.filter(declaration => declaration.group === group), model.declarationOrder[group], group);
    }
    orderByName(model.buildOptions.filter(option => option.field), model.buildOptionFieldOrder, "BuildOptions fields");
    const declarations = [...compiler, ...model.watchOptions, ...model.typeAcquisition, ...model.buildOptions, ...model.rootOptions, ...Object.values(model.elements)];
    for (const declaration of declarations) {
        if (declaration.kind === "Enum") {
            assert(model.enumMaps[declaration.name], `Missing enum map: ${declaration.name}`);
        }
        if (declaration.kind === "List" || declaration.kind === "ListOrElement") {
            assert(model.elements[declaration.name], `Missing list element: ${declaration.name}`);
        }
        for (const value of Object.values(declaration)) {
            if (typeof value === "object" && value !== null && "go" in value) {
                assert(/^(?:core|diagnostics)\.[A-Za-z_]\w*$|^extraValidation(?:Spec|Locale|None)$/.test(value.go), `Invalid Go reference: ${value.go}`);
            }
        }
    }
    for (const [name, map] of Object.entries(model.enumMaps)) {
        assert(map.values.length, `Empty enum map: ${name}`);
        const keys = map.values.map(entry => entry.name);
        assert.equal(new Set(keys).size, keys.length, `Duplicate enum keys: ${name}`);
        assert(keys.every(key => key === key.toLowerCase()), `Enum keys must be lowercase: ${name}`);
        for (const entry of map.values) {
            if (typeof entry.value === "object") assert(constants.has(entry.value.go), `Unknown enum constant: ${entry.value.go}`);
        }
    }
}

function coreOptions(): string {
    const fields = options.compilerOptions.map(option => {
        const comments = [
            ...(option.comment ? [option.comment] : []),
            ...(option.deprecated ? ["Deprecated: Do not use outside of options parsing and validation."] : []),
        ].map(comment => `// ${comment}\n`).join("");
        const tags = [`json:"${option.name},omitzero"`, ...(option.deprecated ? ['deprecated:"true"'] : []), ...(option.internal ? ['internal:"true"'] : [])];
        return `${comments}${fieldName(option)} ${option.type} \`${tags.join(" ")}\``;
    });
    return `${header}
package core

import "github.com/microsoft/TypeScript/tsc/internal/collections"

// CompilerOptions contains the compiler options exposed by the API.
type CompilerOptions struct {
    _ noCopy
    ${fields.join("\n")}
}

// Clone creates a shallow copy of the CompilerOptions.
func (options *CompilerOptions) Clone() *CompilerOptions {
    return &CompilerOptions{
        ${options.compilerOptions.map(option => `${fieldName(option)}: options.${fieldName(option)},`).join("\n")}
    }
}
`;
}

function storedOptions(name: string, declarations: StoredDeclaration[], omitZero: boolean): string {
    return `${header}
package core

type ${name} struct {
${name === "BuildOptions" ? "_ noCopy\n" : ""}
${declarations.map(option => `${option.field.comment ? "\n" + option.field.comment.split("\n").map(line => line ? "// " + line : "").join("\n") + "\n" : ""}${option.field.name} ${option.field.type} \`json:"${option.name}${omitZero ? ",omitzero" : ""}"\``).join("\n")}
}
`;
}

function zeroValue(option: CompilerOption): string {
    const kind = optionKind(option);
    return kind === "Boolean" ? "core.TSUnknown" : kind === "String" ? '""' : kind === "Enum" ? "0" : "nil";
}

function transpileOptions(): string {
    const clearedOptions = options.compilerOptions.filter(option => option.declarations?.some(declaration => typeof declaration.transpileOptionValue === "object" && declaration.transpileOptionValue.go === "core.TSUnknown"));
    return `${header}
package transpile

import "github.com/microsoft/TypeScript/tsc/internal/core"

func clearOptionsForTranspile(options *core.CompilerOptions) {
${clearedOptions.map(option => `options.${fieldName(option)} = ${zeroValue(option)}`).join("\n")}
}
`;
}

export function generateBuildInfoOptions(model = options): string {
    const storedOptions = model.compilerOptions.filter(option => option.declarations?.some(declaration => declaration.affectsBuildInfo));
    return `${header}
package tsoptions

import "github.com/microsoft/TypeScript/tsc/internal/core"

// ForEachCompilerOptionAffectingBuildInfo visits nonzero options in CompilerOptions field order.
func ForEachCompilerOptionAffectingBuildInfo(options *core.CompilerOptions, fn func(option *CommandLineOption, value any)) {
${
        storedOptions.map(option =>
            `if options.${fieldName(option)} != ${zeroValue(option)} {
    fn(CommandLineCompilerOptionsMap.Get(${JSON.stringify(option.name)}), options.${fieldName(option)})
}`
        ).join("\n")
    }
}
`;
}

export function generateOptionComparisons(model = options): string {
    const comparisons = [
        ["SemanticDiagnostics", "affectsSemanticDiagnostics"],
        ["DeclarationPath", "affectsDeclarationPath"],
        ["Emit", "affectsEmit"],
    ] as const;
    return `${header}
package tsoptions

import "github.com/microsoft/TypeScript/tsc/internal/core"

${
        comparisons.map(([name, flag]) => {
            const expressions = model.compilerOptions.flatMap(option => {
                const declaration = option.declarations?.find(declaration => declaration[flag]);
                if (!declaration) return [];
                const kind = optionKind(option);
                assert(kind === "Boolean" || kind === "String" || kind === "Enum", `Unsupported comparison type for ${option.name}: ${option.type}`);
                const value = (receiver: string) => {
                    const field = `${receiver}.${fieldName(option)}`;
                    if (declaration.strictFlag) return `${receiver}.GetStrictOptionValue(${field})`;
                    if (declaration.allowJsFlag) return `${receiver}.GetAllowJS()`;
                    return field;
                };
                return [`${value("oldOptions")} != ${value("newOptions")}`];
            });
            return `func CompilerOptionsAffect${name}(oldOptions *core.CompilerOptions, newOptions *core.CompilerOptions) bool {
    if oldOptions == newOptions { return false }
    if oldOptions == nil || newOptions == nil { return true }
    return ${expressions.join(" ||\n") || "false"}
}
`;
        }).join("\n")
    }
`;
}

