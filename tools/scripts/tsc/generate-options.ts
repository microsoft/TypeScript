function declarationLiteral(declaration: Declaration): string {
    const { name, kind, comment, ...metadata } = declaration;
    const properties = [`Name: ${JSON.stringify(name)},`, `Kind: CommandLineOptionType${kind},`];
    for (const [key, value] of Object.entries(metadata)) {
        if (key === "group" || key === "jsconfigDefault" || key === "field" || key === "variable" || key === "elementOptions" || key === "documentationAnchor" || key === "schemaDescription") continue;
        const goName = privateMetadata.has(key) ? key : key[0].toUpperCase() + key.slice(1);
        properties.push(`${goName}: ${goValue(value)},`);
    }
    return `${comment ? "// " + comment.replaceAll("\n", "\n// ") + "\n" : ""}{\n${properties.join("\n")}\n}`;
}

function declarations(): string {
    const all = compilerDeclarations();
    const groups = ["commonOptionsWithBuild", "optionsForCompiler"] as const;
    const arrays: [string, Declaration[]][] = [
        ...groups.map(group => [group, orderByName(all.filter(declaration => declaration.group === group), options.declarationOrder[group], group)] as [string, Declaration[]]),
        ["OptionsForWatch", options.watchOptions],
        ["typeAcquisitionDecls", options.typeAcquisition],
    ];
    return `${header}
package tsoptions

import (
    "slices"

    "github.com/microsoft/TypeScript/tsc/internal/core"
    "github.com/microsoft/TypeScript/tsc/internal/diagnostics"
)

var OptionsDeclarations = slices.Concat(commonOptionsWithBuild, optionsForCompiler)

var BuildOpts = slices.Concat(commonOptionsWithBuild, OptionsForBuild)

${arrays.map(([name, values]) => `var ${name} = []*CommandLineOption{\n${values.map(declaration => declarationLiteral(declaration) + ",").join("\n")}\n}`).join("\n\n")}

var commandLineOptionElements = map[string]*CommandLineOption{
${Object.entries(options.elements).map(([name, declaration]) => `${JSON.stringify(name)}: ${declarationLiteral(declaration)},`).join("\n")}
}

var TscBuildOption = CommandLineOption${declarationLiteral(options.buildOptions[0])}

var OptionsForBuild = []*CommandLineOption{
    &TscBuildOption,
    ${options.buildOptions.slice(1).map(option => declarationLiteral(option) + ",").join("\n")}
}
`;
}

function rootDeclarations(): string {
    const elementOptions = {
        compilerOptions: "CommandLineCompilerOptionsMap",
        typeAcquisition: "commandLineOptionsToMap(typeAcquisitionDecls)",
        extends: `commandLineOptionsToMap([]*CommandLineOption{${declarationLiteral(options.elements.extends)}})`,
    };
    return `${header}
package tsoptions

import "github.com/microsoft/TypeScript/tsc/internal/diagnostics"

${
        options.rootOptions.filter(option => option.variable).map(option => {
            let literal = declarationLiteral(option);
            if (option.elementOptions) literal = literal.slice(0, -1) + `ElementOptions: ${elementOptions[option.elementOptions]},\n}`;
            return `var ${option.variable} = &CommandLineOption${literal}`;
        }).join("\n\n")
    }

var tsconfigRootOptionsMap = &CommandLineOption{
    Name: "undefined",
    Kind: CommandLineOptionTypeObject,
    ElementOptions: commandLineOptionsToMap([]*CommandLineOption{
        ${options.rootOptions.map(option => (option.variable ?? declarationLiteral(option)) + ",").join("\n")}
    }),
}
`;
}

