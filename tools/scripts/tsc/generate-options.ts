function parserAssignment(option: CompilerOption): string {
    const target = `allOptions.${fieldName(option)}`;
    if (option.parser === "lib") {
        return `if libs, ok := value.([]string); ok { ${target} = libs } else { ${target} = ParseStringArray(value) }`;
    }
    if (option.parser === "plugins") {
        return `if plugins, ok := value.([]any); ok {
            ${target} = core.Map(plugins, func(plugin any) core.PluginImport {
                if pluginMap, isMap := plugin.(*collections.OrderedMap[string, any]); isMap {
                    return core.PluginImport{Name: ParseString(pluginMap.GetOrZero("name"))}
                }
                return core.PluginImport{}
            })
        }`;
    }
    const functions: Partial<Record<CompilerOption["type"], string>> = {
        "Tristate": "ParseTristate",
        "string": "ParseString",
        "*int": "parseNumber",
        "[]string": "ParseStringArray",
        "*collections.OrderedMap[string, []string]": "parseStringMap",
    };
    const parser = functions[option.type];
    assert(option.type !== "[]PluginImport", "Plugin options require the plugin parser");
    return `${target} = ${parser ?? `floatOrInt32ToFlag[core.${option.type}]`}(value)`;
}

function parser(): string {
    return `${header}
package tsoptions

import (
    "github.com/microsoft/TypeScript/tsc/internal/collections"
    "github.com/microsoft/TypeScript/tsc/internal/core"
    "github.com/microsoft/TypeScript/tsc/internal/tspath"
)

func parseCompilerOptions(key string, value any, allOptions *core.CompilerOptions) (foundKey bool) {
    if option := CommandLineCompilerOptionsMap.Get(key); option != nil { key = option.Name }
    switch key {
    ${options.compilerOptions.map(option => `case ${[option.name, ...(option.parseAliases ?? [])].map(name => JSON.stringify(name)).join(", ")}:\n${parserAssignment(option)}`).join("\n")}
    default:
        return false
    }
    return true
}

func getDefaultCompilerOptions(configFileName string) *core.CompilerOptions {
    if configFileName != "" && tspath.GetBaseFileName(configFileName) == "jsconfig.json" {
        return &core.CompilerOptions{
        ${
        options.compilerOptions.filter(option => option.jsconfigDefault !== undefined).map(option => {
            const value = option.jsconfigDefault!;
            const expression = typeof value === "boolean" ? `core.TS${value ? "True" : "False"}` : typeof value === "number" ? `new(${value})` : JSON.stringify(value);
            return `${fieldName(option)}: ${expression},`;
        }).join("\n")
    }
        }
    }
    return &core.CompilerOptions{}
}

func getDefaultTypeAcquisition(configFileName string) *core.TypeAcquisition {
    if configFileName != "" && tspath.GetBaseFileName(configFileName) == "jsconfig.json" {
        return &core.TypeAcquisition{
            ${options.typeAcquisition.filter(option => option.jsconfigDefault !== undefined).map(option => `${option.field.name}: core.TS${option.jsconfigDefault ? "True" : "False"},`).join("\n")}
        }
    }
    return &core.TypeAcquisition{}
}
`;
}

function storedParser(name: string, declarations: StoredDeclaration[], guardNull: boolean): string {
    return `func Parse${name}(key string, value any, allOptions *core.${name}) []*ast.Diagnostic {
    ${guardNull ? "if value == nil { return nil }" : ""}
    if allOptions == nil { return nil }
    ${name === "BuildOptions" ? "if option := BuildNameMap.Get(key); option != nil { key = option.Name }" : ""}
    switch key {
    ${
        declarations.map(option => {
            const stored: CompilerOption = { name: option.name, goName: option.field.name, type: option.field.type };
            const assignment = option.kind === "Enum"
                ? `if value != nil { allOptions.${option.field.name} = value.(core.${option.field.type}) }`
                : parserAssignment(stored);
            return `case ${JSON.stringify(option.name)}:\n${assignment}`;
        }).join("\n")
    }
    }
    return nil
}
`;
}

export function generateOptions(): Map<string, string> {
    validateOptions(options);
    const buildOptions = options.buildOptions.filter((option): option is StoredDeclaration => option.field !== undefined);
    return new Map([
        ["tsc/internal/core/compileroptions_generated.go", coreOptions()],
        ["tsc/internal/core/optionenums_generated.go", numericEnums()],
        ["tsc/internal/core/watchoptions_generated.go", storedOptions("WatchOptions", options.watchOptions, false)],
        ["tsc/internal/core/typeacquisition_generated.go", storedOptions("TypeAcquisition", options.typeAcquisition, true)],
        ["tsc/internal/core/buildoptions_generated.go", storedOptions("BuildOptions", orderByName(buildOptions, options.buildOptionFieldOrder, "BuildOptions fields"), true)],
        ["tsc/internal/transpile/compileroptions_generated.go", transpileOptions()],
        ["tsc/internal/tsoptions/comparisons_generated.go", generateOptionComparisons()],
        ["tsc/internal/tsoptions/buildinfo_generated.go", generateBuildInfoOptions()],
        ["tsc/internal/tsoptions/declarations_generated.go", declarations()],
        ["tsc/internal/tsoptions/rootoptions_generated.go", rootDeclarations()],
        ["tsc/internal/tsoptions/enummaps_generated.go", enumMaps()],
        ["tsc/internal/tsoptions/compileroptions_generated.go", parser()],
        [
            "tsc/internal/tsoptions/otheroptions_generated.go",
            `${header}
package tsoptions

import (
    "github.com/microsoft/TypeScript/tsc/internal/ast"
    "github.com/microsoft/TypeScript/tsc/internal/core"
)

${storedParser("WatchOptions", options.watchOptions, false)}
${storedParser("TypeAcquisition", options.typeAcquisition, true)}
${storedParser("BuildOptions", buildOptions, true)}
`,
        ],
        ...(["tsconfig", "jsconfig"] as const).map(name => [`tsc/internal/tsoptions/schemas/${name}.schema.json`, JSON.stringify(generateConfigSchema(name), null, 4) + "\n"] as [string, string]),
    ]);
}

export default async function generate(force = false): Promise<void> {
    const inputs = [...sourceFiles.map(file => path.join(import.meta.dirname, file)), diagnosticsFile];
    const outputs = generateOptions();
    const changed: GeneratedFile[] = [];
    for (const [fileName, content] of outputs) {
        const file = new GeneratedFile(path.join(repoRoot, fileName), inputs);
        if (file.isCurrent(force)) continue;
        file.write(content);
        changed.push(file);
    }
    if (changed.length) {
        await formatFiles(changed.map(file => file.fileName));
        for (const file of changed) file.markCurrent();
    }
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
    await generate(parseGeneratorArgs({}).force);
}
